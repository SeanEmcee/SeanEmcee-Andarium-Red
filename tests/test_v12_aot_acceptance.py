"""AOT metadata policy checks: never treat an archive candidate as acceptance."""
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
import aot_artifact_pipeline as aot


def candidate(archive='yes'):
    return ('# Generated by upstream AOT artifact tool\n'
            'LINEAGE24_ACCEPTED_AOT_SCHEMA=1\n'
            'LINEAGE24_ACCEPTED_AOT_RELEASE_ID=android17-check\n'
            f'LINEAGE24_ACCEPTED_AOT_ARTIFACT_SHA256={"a"*64}\n'
            f'LINEAGE24_ACCEPTED_AOT_BLOB_SHA256={"b"*64}\n'
            'LINEAGE24_ACCEPTED_AOT_BLOB_VERSION=3\n'
            f'LINEAGE24_ACCEPTED_AOT_ARCHIVES={archive}\n')


class AOTGateTests(unittest.TestCase):
    def test_valid_archive_candidate_can_be_inspected_but_not_applied(self):
        entries=aot.validate_candidate(candidate(),archive_candidate=True)
        self.assertEqual(entries['LINEAGE24_ACCEPTED_AOT_RELEASE_ID'],'android17-check')
        self.assertEqual(entries['LINEAGE24_ACCEPTED_AOT_ARCHIVES'],'yes')

    def test_false_archive_claim_rejected(self):
        with self.assertRaisesRegex(ValueError,'archive policy'):
            aot.validate_candidate(candidate('no'),archive_candidate=True)
        with self.assertRaisesRegex(ValueError,'archive policy'):
            aot.validate_candidate(candidate('yes'),archive_candidate=False)

    def test_missing_or_duplicate_metadata_rejected(self):
        with self.assertRaisesRegex(ValueError,'missing required'):
            aot.validate_candidate(candidate().replace('LINEAGE24_ACCEPTED_AOT_SCHEMA=1\n',''),archive_candidate=True)
        with self.assertRaisesRegex(ValueError,'duplicated'):
            aot.validate_candidate(candidate()+'LINEAGE24_ACCEPTED_AOT_SCHEMA=1\n',archive_candidate=True)

    def test_corrupt_digest_rejected(self):
        with self.assertRaisesRegex(ValueError,'digest'):
            aot.validate_candidate(candidate().replace('a'*64,'BAD'),archive_candidate=True)

    def test_unknown_key_cannot_sneak_into_descriptor(self):
        with self.assertRaisesRegex(ValueError,'unknown'):
            aot.validate_candidate(candidate()+'ACCEPT_ALL_UNTESTED=1\n',archive_candidate=True)

    def test_verifier_must_use_artifact_release_and_candidate(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp)
            artifact=root/'artifact';release=root/'release';candidate_file=root/'candidate.env'
            captured=[]
            def run(cmd,**kwargs):
                captured.append((cmd,kwargs))
                class Completed: returncode=0; stderr=''; stdout='verified'
                return Completed()
            with patch.object(aot.subprocess, 'run', side_effect=run):
                aot.validate_against_upstream(root,artifact,release,candidate_file)
            self.assertEqual(len(captured),1)
            self.assertIn('--accepted',captured[0][0])
            self.assertIn(str(candidate_file),captured[0][0])
            self.assertIn('--release',captured[0][0])
            self.assertIn('--artifact',captured[0][0])

    def test_verifier_failure_blocks_candidate(self):
        with tempfile.TemporaryDirectory() as temp:
            class Failed: returncode=1; stderr='digest does not match release';stdout=''
            with patch.object(aot.subprocess,'run',return_value=Failed()):
                with self.assertRaisesRegex(RuntimeError,'Upstream rejected'):
                    root=Path(temp)
                    aot.validate_against_upstream(root,root/'artifact',root/'release',root/'candidate.env')


if __name__=='__main__':unittest.main()
